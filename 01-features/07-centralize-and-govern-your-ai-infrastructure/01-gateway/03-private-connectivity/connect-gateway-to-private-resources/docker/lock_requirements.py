"""Regenerate both server locks; dependency upgrades require explicit --upgrade.

Use uv 0.9.28. Universal resolution retains platform markers instead of silently
omitting Linux/Windows dependencies when this script runs on a Mac. Installing
or testing an application remains a separate operation.
"""
import argparse
import os
from pathlib import Path
import re
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent
HEADER = "# Generated by docker/lock_requirements.py with uv 0.9.28.\n# Universal CPython 3.12+ graph; use --upgrade explicitly to change existing pins.\n"


def pins(text):
    return {name.lower().replace('_', '-').replace('.', '-'): version
            for name, version in re.findall(r'^([A-Za-z0-9_.-]+)==([^\s;\\]+)', text, re.M)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Resolve and compare without modifying either lock')
    parser.add_argument('--upgrade', action='store_true', help='Explicitly refresh compatible dependencies; revalidate both servers')
    args = parser.parse_args()
    version = subprocess.check_output(['uv', '--version'], text=True).split()
    if version[:2] != ['uv', '0.9.28']:
        parser.error('Use uv 0.9.28 for reproducible generation; do not upgrade the dependency graph implicitly')
    primary = ROOT / 'fastmcp-mock/requirements.txt'
    before = pins(primary.read_text())
    with tempfile.TemporaryDirectory(prefix='vpc-lock-') as directory:
        output = Path(directory) / 'requirements.txt'
        selection = ['--upgrade'] if args.upgrade else ['-c', str(primary)]
        subprocess.run(['uv', 'pip', 'compile', '--universal', '--python-version', '3.12', '--generate-hashes',
                        '--no-build', '--no-header', '--no-annotate', '--no-emit-index-url', *selection,
                        str(ROOT / 'requirements.in'), '-o', str(output)],
                       check=True, env={**os.environ, 'UV_KEYRING_PROVIDER': 'disabled'})
        result = HEADER + output.read_text()
    after = pins(result)
    declared = pins((ROOT / 'requirements.in').read_text())
    if any(after.get(name) != version for name, version in declared.items()):
        raise RuntimeError('Resolved graph does not match the explicit server inputs')
    if not args.upgrade and any(after.get(name) != value for name, value in before.items()):
        raise RuntimeError('Existing pin drift refused; use --upgrade and revalidate deliberately')
    for name in ('fastmcp-mock', 'stock-mcp-mock'):
        path = ROOT / name / 'requirements.txt'
        if args.check:
            if path.read_text() != result:
                raise RuntimeError(f'{path} differs from the constrained universal resolution')
        else:
            path.write_text(result)
    print('Both universal hash locks match; ' + ('explicit upgrade completed.' if args.upgrade else 'no existing version changed.'))


if __name__ == '__main__':
    main()
