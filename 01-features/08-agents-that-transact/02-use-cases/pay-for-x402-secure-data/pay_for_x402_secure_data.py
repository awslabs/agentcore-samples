# ── §10. Cleanup ─────────────────────────────────────────────────────────────
def _safe_delete(fn, label, **kwargs):
    try:
        fn(**kwargs)
        print(f"  ✅ Deleted: {label}")
    except botocore.exceptions.ClientError as exc:
        code = exc.response["Error"]["Code"]
        msg = exc.response["Error"].get("Message", "")
        if code == "ResourceNotFoundException" or (code == "AccessDeniedException" and "not found" in msg.lower()):
            print(f"  ⚠️  Not found: {label}")
        else:
            raise


def cleanup(cp_client, mgmt_client) -> None:
    # Best-effort: cleanup must proceed even if the instrument is already gone,
    # so fall back to USER_ID rather than aborting the teardown.
    payment_user_id = USER_ID
    with contextlib.suppress(Exception):
        payment_user_id = mgmt_client.get_payment_instrument(
            paymentManagerArn=MANAGER_ARN, paymentInstrumentId=PAYMENT_INSTRUMENT_ID, userId=USER_ID
        )["paymentInstrument"]["userId"]

    if PAYMENT_SESSION_ID:
        _safe_delete(
            mgmt_client.delete_payment_session,
            f"Session {PAYMENT_SESSION_ID}",
            paymentManagerArn=MANAGER_ARN,
            paymentSessionId=PAYMENT_SESSION_ID,
            userId=payment_user_id,
        )
    if PAYMENT_INSTRUMENT_ID and PAYMENT_CONNECTOR_ID:
        _safe_delete(
            mgmt_client.delete_payment_instrument,
            f"Instrument {PAYMENT_INSTRUMENT_ID}",
            paymentManagerArn=MANAGER_ARN,
            paymentConnectorId=PAYMENT_CONNECTOR_ID,
            paymentInstrumentId=PAYMENT_INSTRUMENT_ID,
            userId=payment_user_id,
        )
    if PAYMENT_CONNECTOR_ID:
        _safe_delete(
            cp_client.delete_payment_connector,
            f"Connector {PAYMENT_CONNECTOR_ID}",
            paymentManagerId=MANAGER_ID,
            paymentConnectorId=PAYMENT_CONNECTOR_ID,
            clientToken=_client_token(),
        )
    _safe_delete(
        cp_client.delete_payment_manager,
        f"Manager {MANAGER_ID}",
        paymentManagerId=MANAGER_ID,
        clientToken=_client_token(),
    )
    if CREDENTIAL_PROVIDER_ARN:
        _safe_delete(
            cp_client.delete_payment_credential_provider,
            f"Credential provider {CREDENTIAL_PROVIDER_ARN.rsplit('/', 1)[-1]}",
            name=CREDENTIAL_PROVIDER_ARN.rsplit("/", 1)[-1],
        )

    write_env_updates(
        {
            k: ""
            for k in (
                "MANAGER_ARN",
                "PAYMENT_CONNECTOR_ID",
                "CREDENTIAL_PROVIDER_ARN",
                "PAYMENT_INSTRUMENT_ID",
                "PAYMENT_SESSION_ID",
                "WALLET_ADDRESS",
            )
        }
    )
    # Fixed command list (no shell, no untrusted input).
    subprocess.run(["bash", "test/integration/destroy-agent.sh"], cwd=HERE, check=False)  # nosec B603

    _remove_local_artifacts()
    print("\n✅ Cleanup complete.")


def _remove_local_artifacts() -> None:
    """Remove the local CDK build artifacts (venv, cdk.out, outputs.json, caches).

    Mirrors §10.3 of the workshop notebook. AWS resources are already torn down
    above; this leaves only the tracked source files in the use-case folder.
    """
    targets = [
        HERE / "agent" / "cdk" / ".venv",
        HERE / "agent" / "cdk" / "cdk.out",
        HERE / "agent" / "cdk" / "outputs.json",
        HERE / "agent" / "cdk" / "__pycache__",
        HERE / "agent" / "container" / "__pycache__",
        HERE / "__pycache__",
    ]
    print("\n── Local build artifacts ──")
    for path in targets:
        if not path.exists():
            print(f"  ↷ skip (absent): {path.relative_to(HERE)}")
            continue
        if path.is_dir():
            shutil.rmtree(path)
        else:
            path.unlink()
        print(f"  🗑️  removed: {path.relative_to(HERE)}")


