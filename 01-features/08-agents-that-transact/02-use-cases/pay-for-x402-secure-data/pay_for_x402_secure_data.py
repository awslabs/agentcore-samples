def _client_token() -> str:
    """AgentCore payments requires clientToken >= 33 chars (idempotency token)."""
    return f"{uuid.uuid4()}-{uuid.uuid4().hex[:8]}"


def _safe_name(prefix: str) -> str:
    name = f"{prefix}{uuid.uuid4().hex[:8]}"
    assert re.match(r"^[a-zA-Z][a-zA-Z0-9]{0,47}$", name), name
    return name


def _env_flag(name: str) -> bool:
    """True if the named .env gate is set to 1/true/yes (default off)."""
    return os.environ.get(name, "0").strip().lower() in ("1", "true", "yes")


def _confirm_section(title: str, body_lines: list[str], action_label: str, require_yes: bool = False) -> bool:
    """Show a framed banner + body, then prompt for confirmation.

    Default: Enter runs the step, q + Enter skips it. When require_yes is set
    (used for destructive steps like cleanup), the default flips to skip — the
    user must type 'yes' to proceed, and anything else is treated as skip.
    """
    print("\n" + "=" * 72)
    print(f"  {title}")
    print("=" * 72)
    for line in body_lines:
        print(line)
    if require_yes:
        print(f"\n  ▶▶ Type 'yes' + Enter to {action_label}. Anything else skips.")
        return input("     [type 'yes' to confirm | Enter to skip] ").strip().lower() in ("yes", "y")
    print(f"\n  ▶▶ Press Enter to {action_label}, or press q + Enter to skip.")
    return input("     [Enter to continue | q to skip] ").strip().lower() not in ("q", "quit", "skip", "n", "no")


def _is_set(value: str) -> bool:
    return bool(value) and not value.startswith("<")


def _run_env_check() -> None:
    # Non-secret values are safe to echo. Secret values are kept in a separate
    # map and are ONLY ever checked for presence — their values never flow into
    # a printed string, so nothing sensitive is logged in clear text.
    visible = {
        "AWS_REGION": AWS_REGION,
        "CONTROL_PLANE_ROLE_ARN": CONTROL_PLANE_ROLE_ARN,
        "MANAGEMENT_ROLE_ARN": MANAGEMENT_ROLE_ARN,
        "PROCESS_PAYMENT_ROLE_ARN": PROCESS_PAYMENT_ROLE_ARN,
        "RESOURCE_RETRIEVAL_ROLE_ARN": RESOURCE_RETRIEVAL_ROLE_ARN,
        "INSTRUMENT_EMAIL": INSTRUMENT_EMAIL,
    }
    # These are the Coinbase env-var NAMES to display (not their values). Named
    # without "secret"/"key" so static analysis does not misclassify the printed
    # variable name as a sensitive value.
    coinbase_env_names = ("COINBASE_API_KEY_ID", "COINBASE_API_KEY_SECRET", "COINBASE_WALLET_SECRET")

    print("=== Environment check ===")
    missing = []
    for key, value in visible.items():
        ok = _is_set(value)
        print(f"  {'✅' if ok else '❌ MISSING'}  {key}: {value if ok else '(missing)'}")
        if not ok:
            missing.append(key)

    # Check the secrets for presence only. The secret values (and any variable
    # derived from them) are never referenced in a printed string — only the
    # literal key name is appended to `missing`, so nothing sensitive is logged.
    if not _is_set(COINBASE_API_KEY_ID):
        missing.append("COINBASE_API_KEY_ID")
    if not _is_set(COINBASE_API_KEY_SECRET):
        missing.append("COINBASE_API_KEY_SECRET")
    if not _is_set(COINBASE_WALLET_SECRET):
        missing.append("COINBASE_WALLET_SECRET")

    # Render status from the (literal) missing-name list, so the printed line
    # never references a secret value or a secret-derived variable.
    for name in coinbase_env_names:
        present = name not in missing
        print(f"  {'✅' if present else '❌ MISSING'}  {name}: {'[redacted]' if present else '(missing)'}")

    if INSTRUMENT_EMAIL.lower().endswith("@example.com"):
        sys.exit("INSTRUMENT_EMAIL must be a REAL, deliverable address — not an @example.com placeholder.")
    if missing:
        sys.exit(f"\n❌ {len(missing)} required value(s) missing in .env. Fix them, save, then re-run.")
    print("\n✅ Environment check passed.\n")


# ── §3. Guardrail demo (mocks, no AWS, no money) ─────────────────────────────
def guardrail_demo() -> None:
    from x402_services import (
        DEFAULT_SERVICE_ID,
        HEURIST_YAHOO_FINANCE_OPERATIONS,
        TrustedX402ServiceGateway,
        resolve_heurist_base_url,
        use_request_trust_state,
    )

    print("=== §3. Trust guardrail demo (mocks — no AWS calls, no payments) ===")
    target_url = resolve_heurist_base_url()

    class DemoTrustClient:
        def __init__(self, result):
            self.result = result

        def score_endpoint(self, url, headers=None):
            return self.result

    class DemoServiceClient:
        def call_operation(self, operation, payload, headers=None):
            return {"operation": operation, "data": "<mocked market data>"}

    def make_gateway(trust_result):
        services = {
            DEFAULT_SERVICE_ID: {
                "base_url": target_url,
                "operations": HEURIST_YAHOO_FINANCE_OPERATIONS,
                "client": DemoServiceClient(),
            }
        }
        return TrustedX402ServiceGateway(
            services=services,
            trust_client=DemoTrustClient(trust_result),
            trust_threshold=50,
            fail_closed=True,
        )

    for label, trust in (
        ("Approved (score 91)", {"overall_score": 91, "risk_level": "low", "is_scam": False}),
        ("Blocked — low score (23)", {"overall_score": 23, "risk_level": "high", "is_scam": False}),
        ("Blocked — scam flagged", {"overall_score": 88, "risk_level": "critical", "is_scam": True}),
    ):
        with use_request_trust_state():
            gw = make_gateway(trust)
            gw.check_x402_endpoint_trust(DEFAULT_SERVICE_ID)
            result = gw.call_trusted_x402_service(DEFAULT_SERVICE_ID, "quote_snapshot", {"symbols": "AAPL"})
            status = result.get("status", "called") if isinstance(result, dict) else result
            print(f"  {label} -> {'🚫 ' + result['reason'] if status == 'blocked' else '✅ target called'}")
    print("\n  The target service is only reached on the approved path.\n")


# ── §4. Set up AgentCore payments (credential provider, manager, connector) ──
def build_control_client() -> boto3.client:
    for name, val in (
        ("CONTROL_PLANE_ROLE_ARN", CONTROL_PLANE_ROLE_ARN),
        ("RESOURCE_RETRIEVAL_ROLE_ARN", RESOURCE_RETRIEVAL_ROLE_ARN),
    ):
        if not val:
            sys.exit(f"Missing {name}. Run bash test/integration/setup-roles.sh.")
    print("Assuming ControlPlaneRole...")
    cp_session = assume_role(Session(region_name=AWS_REGION), CONTROL_PLANE_ROLE_ARN, "x402-secure-cp")
    return cp_session.client("bedrock-agentcore-control")


def setup_payments(cp_client) -> None:
    global CREDENTIAL_PROVIDER_ARN, MANAGER_ARN, MANAGER_ID, PAYMENT_CONNECTOR_ID

    if CREDENTIAL_PROVIDER_ARN:
        print("↷ CREDENTIAL_PROVIDER_ARN already set, skipping credential provider create")
    else:
        resp = idempotent_create(
            cp_client.create_payment_credential_provider,
            conflict_msg="Credential provider already exists",
            name=_safe_name("CoinbaseCdp"),
            credentialProviderVendor="CoinbaseCDP",
            providerConfigurationInput={
                "coinbaseCdpConfiguration": {
                    "apiKeyId": COINBASE_API_KEY_ID,
                    "apiKeySecret": COINBASE_API_KEY_SECRET,
                    "walletSecret": COINBASE_WALLET_SECRET,
                }
            },
        )
        if resp is None:
            sys.exit("Credential provider already exists — rename or delete it.")
        CREDENTIAL_PROVIDER_ARN = resp["credentialProviderArn"]
        write_env_updates({"CREDENTIAL_PROVIDER_ARN": CREDENTIAL_PROVIDER_ARN})
        print("✅ Credential provider created")

    if MANAGER_ARN:
        print("↷ MANAGER_ARN already set, skipping manager create")
    else:
        resp = cp_client.create_payment_manager(
            name=_safe_name("X402SecureData"),
            description="AgentCore payments Pay for Secure Data (x402)",
            authorizerType="AWS_IAM",
            roleArn=RESOURCE_RETRIEVAL_ROLE_ARN,
            clientToken=_client_token(),
        )
        MANAGER_ID = resp["paymentManagerId"]
        MANAGER_ARN = resp["paymentManagerArn"]
        wait_for_status(cp_client.get_payment_manager, expected_status="READY", paymentManagerId=MANAGER_ID)
        write_env_updates({"MANAGER_ARN": MANAGER_ARN})
        print(f"✅ Manager READY: {MANAGER_ARN}")
    MANAGER_ID = MANAGER_ARN.rsplit("/", 1)[-1]

    if PAYMENT_CONNECTOR_ID:
        print("↷ PAYMENT_CONNECTOR_ID already set, skipping connector create")
    else:
        resp = cp_client.create_payment_connector(
            paymentManagerId=MANAGER_ID,
            name=_safe_name("CoinbaseConnector"),
            description="AgentCore payments CoinbaseCDP connector",
            type="CoinbaseCDP",
            credentialProviderConfigurations=[{"coinbaseCDP": {"credentialProviderArn": CREDENTIAL_PROVIDER_ARN}}],
            clientToken=_client_token(),
        )
        PAYMENT_CONNECTOR_ID = resp["paymentConnectorId"]
        wait_for_status(
            cp_client.get_payment_connector,
            expected_status="READY",
            paymentManagerId=MANAGER_ID,
            paymentConnectorId=PAYMENT_CONNECTOR_ID,
        )
        write_env_updates({"PAYMENT_CONNECTOR_ID": PAYMENT_CONNECTOR_ID})
        print(f"✅ Connector READY: {PAYMENT_CONNECTOR_ID}")


